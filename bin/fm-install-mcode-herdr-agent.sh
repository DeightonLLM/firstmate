#!/usr/bin/env bash
# fm-install-mcode-herdr-agent.sh - install the MCode Herdr agent reporting plugin.
#
# Herdr has no built-in adapter for the MCode harness, so an MCode pane carries
# no agent label, reports agent_status "unknown", and keeps its running and
# stopped light dark.
#
# This installer publishes the tracked plugin package into the MCode local
# marketplace, puts the reporter on PATH so the plugin can call it by name,
# refreshes the marketplace snapshot, and enables the plugin for the local
# marketplace.
# A local package needs no install step: mcode plugin add refuses a local
# plugin with LOCAL_PLUGIN_INSTALL_UNSUPPORTED.
#
# The reporter shim is not a convenience wrapper. MCode spawns lifecycle hooks
# with a fixed environment whitelist that carries no HERDR_* variable, so the
# reporter inside the hook would correctly refuse to act, and a hook that did
# reach Herdr would reach the default session rather than the pane's own
# session. The shim recovers the pane identity from the MCode process that
# spawned it, through /proc/<pid>/environ.
#
# Two package rules matter and are enforced here rather than left to a comment:
#   * The package must carry NO root plugin.json. MCode tries its portable
#     "Agent Plugins" reader first whenever a root plugin.json exists, and
#     that reader implements only skills/ and mcp.json with no hooks
#     component, so a hooks-only package is loaded with zero capabilities and
#     dropped as LOCAL_PLUGIN_NO_SUPPORTED_CAPABILITY.
#   * .minimax-plugin/plugin.json must declare its hooks as an array of hook
#     document paths and must name a real icon file that ships in the package.
#
# Usage: fm-install-mcode-herdr-agent.sh [--uninstall]
set -uo pipefail

SELF_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "$SELF_DIR/.." && pwd)"
PKG_SRC="$REPO_ROOT/extensions/mcode-herdr-agent"
PLUGIN_NAME="mcode-herdr-agent"
MARKETPLACE_DIR="${FM_MCODE_MARKETPLACE_DIR:-$HOME/.minimax/plugins}"
BIN_DIR="${FM_HERDR_AGENT_BIN_DIR:-$HOME/.local/bin}"
SHIM="$BIN_DIR/fm-herdr-agent-report.sh"
PUBLISHED="${MARKETPLACE_DIR:?}/$PLUGIN_NAME"

# The shim must call a reporter that outlives this run. The checkout the
# installer happens to run from may be a disposable task worktree, and a shim
# that points into one breaks as soon as that worktree is torn down, so the
# home that owns the fleet wins when it carries the reporter.
REPORTER="$REPO_ROOT/bin/fm-herdr-agent-report.sh"
if [ -n "${FM_HOME:-}" ] && [ -x "${FM_HOME}/bin/fm-herdr-agent-report.sh" ]; then
  REPORTER="${FM_HOME}/bin/fm-herdr-agent-report.sh"
fi

usage() {
  printf 'Usage: %s [--uninstall]\n' "$(basename "$0")"
}

uninstall() {
  if command -v mcode >/dev/null 2>&1; then
    mcode plugin remove "$PLUGIN_NAME@local" >/dev/null 2>&1 || true
  fi
  rm -f "$SHIM"
  rm -rf "${PUBLISHED:?}"
  printf 'Removed %s and %s\n' "$SHIM" "$PUBLISHED"
}

case "${1:-}" in
  "") ;;
  --uninstall)
    uninstall
    exit 0
    ;;
  -h | --help)
    usage
    exit 0
    ;;
  *)
    usage >&2
    exit 2
    ;;
esac

if [ ! -d "$PKG_SRC" ]; then
  printf 'Plugin package not found: %s\n' "$PKG_SRC" >&2
  exit 1
fi

if [ ! -x "$REPORTER" ]; then
  printf 'Reporter is missing or not executable: %s\n' "$REPORTER" >&2
  exit 1
fi

if ! command -v mcode >/dev/null 2>&1; then
  printf 'mcode is not on PATH; install the MCode CLI first.\n' >&2
  exit 1
fi

if [ -f "$PKG_SRC/plugin.json" ]; then
  cat >&2 <<'HIJACK_EOF'
Refusing to publish: the package carries a root plugin.json.

MCode tries its portable "Agent Plugins" reader before its own native reader
whenever a root plugin.json exists. That reader implements only skills/ and
mcp.json, has no hooks component, and a hooks-only package would be discarded
as having no supported capability. Delete the root plugin.json; the MCode
plugin contract lives in .minimax-plugin/plugin.json.
HIJACK_EOF
  exit 1
fi

if [ ! -f "$PKG_SRC/.minimax-plugin/plugin.json" ]; then
  printf 'Native manifest not found: %s\n' "$PKG_SRC/.minimax-plugin/plugin.json" >&2
  exit 1
fi

if ! grep -q '"hooks"[[:space:]]*:[[:space:]]*\[' "$PKG_SRC/.minimax-plugin/plugin.json"; then
  printf '%s\n' \
    'Native manifest must declare "hooks" as an array of hook document paths;' \
    'a bare string is rejected by the MCode manifest reader.' >&2
  exit 1
fi

if [ ! -f "$PKG_SRC/icon.png" ]; then
  printf 'Native manifest names an icon, but the package ships no icon.png.\n' >&2
  exit 1
fi

mkdir -p "$MARKETPLACE_DIR" "$BIN_DIR" || exit 1

rm -rf "${PUBLISHED:?}"
cp -R "$PKG_SRC" "$PUBLISHED" || exit 1

{
  printf '#!/usr/bin/env bash\n'
  printf '# Generated by %s. Do not edit; re-run the installer instead.\n' "$(basename "$0")"
  printf 'REPORTER=%q\n' "$REPORTER"
  cat <<'SHIM_EOF'

# MCode spawns lifecycle hooks with a fixed environment whitelist (PATH, HOME,
# LANG, TERM, SHELL, USER and the temporary-directory and Windows variables,
# plus the plugin root/data and project directories). No HERDR_* variable
# survives, so recover the pane identity from the MCode process that spawned
# this hook: /proc/<pid>/environ keeps the environment the process started with.
inherit_herdr_env() {
  local pid="${1:-$PPID}" depth=0 key value
  while [ -n "$pid" ] && [ "$depth" -lt 4 ]; do
    case "$pid" in
      '' | *[!0-9]*) return 0 ;;
    esac
    [ "$pid" -gt 1 ] 2>/dev/null || return 0
    if [ -r "/proc/$pid/environ" ]; then
      while IFS='=' read -r key value; do
        case "$key" in
          HERDR_ENV | HERDR_PANE_ID | HERDR_SESSION | HERDR_SOCKET_PATH | HERDR_BIN_PATH)
            [ -n "${!key:-}" ] || export "$key=$value"
            ;;
        esac
      done < <(tr '\0' '\n' <"/proc/$pid/environ" 2>/dev/null)
    fi
    [ -n "${HERDR_PANE_ID:-}" ] && return 0
    pid="$(awk '/^PPid:/ {print $2; exit}' "/proc/$pid/status" 2>/dev/null)"
    depth=$((depth + 1))
  done
  return 0
}

inherit_herdr_env

# The reporter refuses to guess a binary; resolve it from PATH when the pane
# environment did not carry one.
if [ -z "${HERDR_BIN_PATH:-}" ] || [ ! -x "${HERDR_BIN_PATH:-}" ]; then
  resolved="$(command -v herdr 2>/dev/null)"
  [ -n "$resolved" ] && export HERDR_BIN_PATH="$resolved"
fi

exec "$REPORTER" "$@"
SHIM_EOF
} >"$SHIM" || exit 1
chmod 0755 "$SHIM"

# A local package is discovered by the directory itself, so there is nothing to
# install: mcode plugin add refuses a local plugin with LOCAL_PLUGIN_INSTALL_UNSUPPORTED.
# Refreshing the marketplace snapshot and enabling the discovered package is the
# supported path, and it leaves the plugin enabled for every later session.
if ! mcode plugin marketplace upgrade >/dev/null 2>&1; then
  printf 'Plugin package published to %s, but mcode plugin marketplace upgrade failed.\n' "$PUBLISHED" >&2
  exit 1
fi

if ! mcode plugin enable "$PLUGIN_NAME@local" >/dev/null 2>&1; then
  printf 'Plugin package published to %s, but mcode plugin enable failed.\n' "$PUBLISHED" >&2
  printf 'Enable it with: mcode plugin enable %s@local\n' "$PLUGIN_NAME" >&2
  exit 1
fi

printf 'Installed %s\n' "$PLUGIN_NAME"
printf 'Publisher on PATH: %s\n' "$SHIM"
printf 'Verify with: herdr agent list\n'
