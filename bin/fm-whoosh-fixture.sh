#!/usr/bin/env bash
set -Eeuo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
RECIPE="$ROOT/data/2026-10-19/fixture-recipe"
STATE="$RECIPE/fixture.env"
ASTRA="$ROOT/data/2026-10-19/whoosh-astra/themes/astra"
CHILD="$ROOT/data/2026-10-19/luna-six/wp-integration/v9-fix/whoosh-port-theme-v9"
ASTRA_VERSION=4.14.0
CHILD_VERSION=9.0.0
DB_IMAGE=mariadb:11.4
WEB_IMAGE=wordpress:php8.3-apache
CLI_IMAGE=wordpress:cli-php8.3
usage() { echo "Usage: $0 {up|health|down}" >&2; exit 2; }
fail() { echo "ERROR: $*" >&2; exit 1; }
[[ $# == 1 ]] || usage
COMMAND=$1
case "$COMMAND" in up|health|down) ;; *) usage ;; esac
command -v docker >/dev/null || fail 'docker is required'
mkdir -p -- "$RECIPE"

load_state() {
  [[ -f "$STATE" ]] || fail "no fixture state at $STATE; run up first"
  # This file is generated by this script; validate every name before Docker use.
  # shellcheck disable=SC1090
  source "$STATE"
  [[ ${ID:-} =~ ^[a-f0-9]{12}$ ]] || fail 'invalid fixture state ID'
  for key in NET DBVOL WPVOL DB WEB CLI; do
    [[ ${!key:-} == "whoosh-fixture-$ID-$key" ]] || fail "invalid state value for $key"
  done
  [[ ${HOST_PORT:-} =~ ^[0-9]+$ ]] || fail 'invalid host port in fixture state'
}
exists() { docker "$1" inspect "$2" >/dev/null 2>&1; }
record_resources() {
  printf 'Fixture ID: %s\nContainer: %s\nContainer: %s\nContainer: %s\nVolume: %s\nVolume: %s\nNetwork: %s\nPort: 127.0.0.1:%s -> %s:80\n' \
    "$ID" "$DB" "$WEB" "$CLI" "$DBVOL" "$WPVOL" "$NET" "$HOST_PORT" "$WEB"
}
health() {
  load_state
  for pair in "container:$DB" "container:$WEB" "container:$CLI" "volume:$DBVOL" "volume:$WPVOL" "network:$NET"; do
    kind=${pair%%:*}; name=${pair#*:}
    case "$kind" in
      container) exists container "$name" || fail "missing fixture container $name" ;;
      volume) exists volume "$name" || fail "missing fixture volume $name" ;;
      network) exists network "$name" || fail "missing fixture network $name" ;;
    esac
  done
  local tmp html active
  tmp=$(mktemp)
  trap 'rm -f -- "$tmp"' RETURN
  local served=0
  for _ in $(seq 1 30); do
    if curl --fail --silent --max-time 4 "http://127.0.0.1:$HOST_PORT/" -o "$tmp" 2>/dev/null \
      && grep -Eqi '<html|<!doctype html' "$tmp" \
      && grep -qi 'wp-content/themes/whoosh-port' "$tmp"; then served=1; break; fi
    sleep 2
  done
  (( served == 1 )) || fail 'HTTP response is not a real WordPress page containing Whoosh theme markup'
  active=$(docker exec "$CLI" wp theme list --status=active --field=name --path=/var/www/html --allow-root | tr '\n' ' ')
  [[ "$active" == *whoosh-port* ]] || fail "Whoosh child is not active according to wp theme list: $active"
  docker exec "$CLI" wp theme get astra --field=version --path=/var/www/html --allow-root | grep -qx "$ASTRA_VERSION" || fail 'Astra 4.14.0 is not installed'
  docker exec "$CLI" wp theme get whoosh-port --field=status --path=/var/www/html --allow-root | grep -qx active || fail 'Whoosh child is not active'
  html=$(grep -Eio 'wp-content/themes/(astra|whoosh-port)[^"<> ]*' "$tmp" | head -n 8 | tr '\n' ' ' || true)
  printf 'HTTP: 200 http://127.0.0.1:%s/\nWordPress markup: PASS (HTML document; Whoosh child asset path present)\nRendered theme asset evidence: %s\nActive theme (wp theme list): %s\nAstra version (wp theme get): %s\nWhoosh child status (wp theme get): active\n' "$HOST_PORT" "$html" "$active" "$ASTRA_VERSION"
}
case "$COMMAND" in
  up)
    if [[ -f "$STATE" ]]; then
      load_state
      echo 'Existing fixture state found; reconciling only its recorded resources.'
      if exists container "$WEB" && exists container "$DB" && exists container "$CLI"; then
        record_resources
        health
        exit 0
      fi
      fail 'partial recorded fixture; run down to remove recorded resources, then up again'
    fi
    [[ -d "$ASTRA" && -f "$ASTRA/style.css" ]] || fail "Astra source missing: $ASTRA"
    [[ -d "$CHILD" && -f "$CHILD/style.css" ]] || fail "Whoosh v9 source missing: $CHILD"
    grep -Eq '^Version:[[:space:]]*4\.14\.0' "$ASTRA/style.css" || fail 'Astra source version is not 4.14.0'
    grep -Eq '^Version:[[:space:]]*9\.0\.0' "$CHILD/style.css" || fail 'Whoosh v9 source version is not 9.0.0'
    grep -Eq '^Template:[[:space:]]*astra' "$CHILD/style.css" || fail 'Whoosh child requires Astra parent'
    ID=$(tr -d '-' </proc/sys/kernel/random/uuid | cut -c1-12)
    NET="whoosh-fixture-$ID-NET"; DBVOL="whoosh-fixture-$ID-DBVOL"; WPVOL="whoosh-fixture-$ID-WPVOL"
    DB="whoosh-fixture-$ID-DB"; WEB="whoosh-fixture-$ID-WEB"; CLI="whoosh-fixture-$ID-CLI"
    HOST_PORT=0
    umask 077
    printf 'ID=%q\nNET=%q\nDBVOL=%q\nWPVOL=%q\nDB=%q\nWEB=%q\nCLI=%q\nHOST_PORT=%q\n' "$ID" "$NET" "$DBVOL" "$WPVOL" "$DB" "$WEB" "$CLI" "$HOST_PORT" >"$STATE"
    trap 'rc=$?; if ((rc)); then echo "Setup failed; recorded resources remain for explicit '$0' down." >&2; fi; exit "$rc"' EXIT
    docker network create "$NET" >/dev/null
    echo "Created network: $NET"
    docker volume create "$DBVOL" >/dev/null
    echo "Created volume: $DBVOL"
    docker volume create "$WPVOL" >/dev/null
    echo "Created volume: $WPVOL"
    docker run -d --name "$DB" --network "$NET" --network-alias db \
      -e MARIADB_DATABASE=wordpress -e MARIADB_USER=wpfixture \
      -e MARIADB_PASSWORD=whoosh-fixture-password -e MARIADB_ROOT_PASSWORD=whoosh-fixture-root \
      -v "$DBVOL:/var/lib/mysql" "$DB_IMAGE" --skip-log-bin >/dev/null
    echo "Created container: $DB"
    docker run -d --name "$WEB" --network "$NET" -p 127.0.0.1::80 \
      -e WORDPRESS_DB_HOST=db -e WORDPRESS_DB_NAME=wordpress -e WORDPRESS_DB_USER=wpfixture \
      -e WORDPRESS_DB_PASSWORD=whoosh-fixture-password -v "$WPVOL:/var/www/html" \
      "$WEB_IMAGE" >/dev/null
    echo "Created container: $WEB"
    docker run -d --name "$CLI" --network "$NET" --user 0:0 \
      -e WORDPRESS_DB_HOST=db -e WORDPRESS_DB_NAME=wordpress -e WORDPRESS_DB_USER=wpfixture \
      -e WORDPRESS_DB_PASSWORD=whoosh-fixture-password \
      -v "$WPVOL:/var/www/html" -v "$ASTRA:/fixture/astra:ro" -v "$CHILD:/fixture/whoosh-port:ro" \
      --entrypoint sh "$CLI_IMAGE" -c 'sleep infinity' >/dev/null
    echo "Created container: $CLI"
    HOST_PORT=$(docker port "$WEB" 80/tcp | sed -E 's/.*:([0-9]+)$/\1/' | head -n1)
    [[ "$HOST_PORT" =~ ^[0-9]+$ ]] || fail 'could not determine assigned loopback port'
    printf 'ID=%q\nNET=%q\nDBVOL=%q\nWPVOL=%q\nDB=%q\nWEB=%q\nCLI=%q\nHOST_PORT=%q\n' "$ID" "$NET" "$DBVOL" "$WPVOL" "$DB" "$WEB" "$CLI" "$HOST_PORT" >"$STATE"
    record_resources
    echo 'Waiting for the new MariaDB container only.'
    db_ready=0
    for _ in $(seq 1 60); do
      if docker exec "$DB" healthcheck.sh --connect --innodb_initialized >/dev/null 2>&1; then db_ready=1; break; fi
      sleep 2
    done
    (( db_ready == 1 )) || fail 'new MariaDB container did not become ready'
    echo 'Waiting for WordPress files initialized by the new web container.'
    for _ in $(seq 1 60); do
      if docker exec "$WEB" test -f /var/www/html/wp-load.php 2>/dev/null; then break; fi
      sleep 2
    done
    docker exec "$WEB" test -f /var/www/html/wp-load.php || fail 'WordPress files were not initialized'
    docker exec "$CLI" cp -a /fixture/astra /var/www/html/wp-content/themes/astra
    docker exec "$CLI" cp -a /fixture/whoosh-port /var/www/html/wp-content/themes/whoosh-port
    docker exec "$CLI" wp core install --path=/var/www/html --url="http://127.0.0.1:$HOST_PORT" \
      --title='Whoosh Disposable Fixture' --admin_user=fixture-admin --admin_password='whoosh-fixture-admin-password' \
      --admin_email=fixture@example.invalid --skip-email --allow-root
    docker exec "$CLI" wp theme activate astra --path=/var/www/html --allow-root
    docker exec "$CLI" wp theme activate whoosh-port --path=/var/www/html --allow-root
    trap - EXIT
    record_resources
    health
    ;;
  health)
    health
    ;;
  down)
    load_state
    failures=0
    echo 'Removing only resources listed in this fixture state:'
    for c in "$CLI" "$WEB" "$DB"; do
      if exists container "$c"; then
        if docker rm -f "$c" >/dev/null; then echo "removed container $c"; else echo "FAILED to remove container $c" >&2; failures=$((failures+1)); fi
      else echo "already absent container $c"; fi
      if exists container "$c"; then echo "FAILED proof: container remains $c" >&2; failures=$((failures+1)); else echo "gone container $c"; fi
    done
    for v in "$WPVOL" "$DBVOL"; do
      if exists volume "$v"; then
        if docker volume rm "$v" >/dev/null; then echo "removed volume $v"; else echo "FAILED to remove volume $v" >&2; failures=$((failures+1)); fi
      else echo "already absent volume $v"; fi
      if exists volume "$v"; then echo "FAILED proof: volume remains $v" >&2; failures=$((failures+1)); else echo "gone volume $v"; fi
    done
    if exists network "$NET"; then
      if docker network rm "$NET" >/dev/null; then echo "removed network $NET"; else echo "FAILED to remove network $NET" >&2; failures=$((failures+1)); fi
    else echo "already absent network $NET"; fi
    if exists network "$NET"; then echo "FAILED proof: network remains $NET" >&2; failures=$((failures+1)); else echo "gone network $NET"; fi
    if (( failures == 0 )); then rm -f -- "$STATE"; echo 'Teardown proof: all recorded containers, volumes and network are absent.'; else echo "Teardown incomplete: $failures removal/proof failure(s); fixture state retained." >&2; exit 1; fi
    ;;
esac
